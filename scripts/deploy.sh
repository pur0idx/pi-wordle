#!/usr/bin/env bash
# One-command deployment:  scripts/deploy.sh [local|pi]
#
#   1. creates the namespace and the daily-answer Secret (random, if missing)
#   2. pins CoreDNS to the control plane (scripts/harden-system.sh)
#   3. applies k8s/overlays/<overlay> with kustomize
#   4. waits until every deployment has all replicas ready
#
# For `pi`, images come from ghcr.io/<owner>/kube-guess-<service>:<tag>:
#   owner  IMAGE_OWNER, else the GitHub owner of `git remote origin`
#   tag    IMAGE_TAG, else the commit of the newest successful CI build on
#          main (needs `gh`), else the tag deployed last time (works offline),
#          else `latest`
# Pinning an exact commit matters: pods use imagePullPolicy IfNotPresent, so
# a moving tag like `latest` would never be re-pulled by Pis that already
# have an older `latest` cached.
set -euo pipefail
cd "$(dirname "$0")/.."

OVERLAY="${1:-local}"
NS=kube-guess
STATE_DIR=.deploy
[[ -d "k8s/overlays/$OVERLAY" ]] || { echo "unknown overlay: $OVERLAY (use local or pi)"; exit 1; }
mkdir -p "$STATE_DIR"

# kubectl acts on whatever cluster is current; say which, and refuse the
# obvious mistake of sending the local overlay somewhere that is not k3d.
CONTEXT=$(kubectl config current-context 2>/dev/null || echo "none")
echo "==> cluster: $CONTEXT  (KUBECONFIG=${KUBECONFIG:-~/.kube/config})"
if [[ "$OVERLAY" == local && "$CONTEXT" != k3d-* ]]; then
  echo "refusing: the local overlay is for a k3d cluster. Run scripts/local-up.sh, or switch context."
  exit 1
fi
kubectl get nodes >/dev/null || { echo "cannot reach cluster '$CONTEXT'"; exit 1; }

resolve_owner() {
  if [[ -n "${IMAGE_OWNER:-}" ]]; then echo "$IMAGE_OWNER"; return; fi
  git remote get-url origin 2>/dev/null | sed -nE 's#.*github\.com[:/]([^/]+)/.*#\1#p'
}

resolve_tag() {
  if [[ -n "${IMAGE_TAG:-}" ]]; then echo "$IMAGE_TAG"; return; fi
  local sha=""
  if command -v gh >/dev/null 2>&1; then
    sha=$(gh run list --workflow build.yml --branch main --event push --status success \
            --limit 1 --json headSha -q '.[0].headSha' 2>/dev/null || true)
  fi
  if [[ -n "$sha" ]]; then echo "$sha"; return; fi
  if [[ -s "$STATE_DIR/last-tag" ]]; then
    echo "  (GitHub unreachable: reusing the last deployed tag)" >&2
    cat "$STATE_DIR/last-tag"; return
  fi
  echo "  (warning: no build found, falling back to :latest)" >&2
  echo latest
}

KUSTOMIZE_DIR="k8s/overlays/$OVERLAY"
TAG=""
if [[ "$OVERLAY" == pi ]]; then
  if grep -q CHANGE_ME k8s/overlays/pi/kustomization.yaml || [[ -n "${IMAGE_TAG:-}${IMAGE_OWNER:-}" ]]; then
    OWNER=$(resolve_owner | tr '[:upper:]' '[:lower:]')
    [[ -n "$OWNER" ]] || { echo "cannot tell the GitHub owner: set IMAGE_OWNER"; exit 1; }
    TAG=$(resolve_tag)
    echo "==> images: ghcr.io/$OWNER/kube-guess-*:$TAG"
    # Generated, git-ignored overlay: base + the resolved image names.
    KUSTOMIZE_DIR="k8s/overlays/.generated"
    mkdir -p "$KUSTOMIZE_DIR"
    {
      echo "# Generated by scripts/deploy.sh. Do not edit."
      echo "apiVersion: kustomize.config.k8s.io/v1beta1"
      echo "kind: Kustomization"
      echo "resources: [../../base]"
      echo "images:"
      for s in frontend gateway word-service evaluator hint-engine; do
        echo "  - { name: kube-guess/$s, newName: ghcr.io/$OWNER/kube-guess-$s, newTag: \"$TAG\" }"
      done
    } > "$KUSTOMIZE_DIR/kustomization.yaml"
  else
    echo "==> images: as pinned in k8s/overlays/pi (scripts/set-registry.sh)"
  fi
fi

kubectl get namespace "$NS" >/dev/null 2>&1 || kubectl create namespace "$NS"

# The secret never lives in git. Every word-service replica reads the same
# value, which is what makes their daily answers agree.
if ! kubectl -n "$NS" get secret kube-guess-secret >/dev/null 2>&1; then
  SECRET="${DAILY_SECRET:-$(openssl rand -hex 32)}"
  kubectl -n "$NS" create secret generic kube-guess-secret --from-literal=DAILY_SECRET="$SECRET"
  echo "created secret kube-guess-secret"
fi

# Images from a private GitHub repo are private on GHCR too. Either make the
# packages public, or export GHCR_USER and GHCR_TOKEN (a PAT with
# read:packages) and every pod in the namespace gets a pull secret.
if [[ -n "${GHCR_TOKEN:-}" ]]; then
  kubectl -n "$NS" create secret docker-registry ghcr-pull \
    --docker-server=ghcr.io --docker-username="${GHCR_USER:?set GHCR_USER}" --docker-password="$GHCR_TOKEN" \
    --dry-run=client -o yaml | kubectl apply -f -
  kubectl -n "$NS" patch serviceaccount default -p '{"imagePullSecrets":[{"name":"ghcr-pull"}]}'
fi

echo "==> pinning CoreDNS to the control plane"
scripts/harden-system.sh

echo "==> applying $KUSTOMIZE_DIR"
kubectl apply -k "$KUSTOMIZE_DIR"

echo "==> waiting for rollouts"
for d in word-service evaluator hint-engine gateway frontend; do
  kubectl -n "$NS" rollout status "deployment/$d" --timeout=600s
done
kubectl -n "$NS" rollout status daemonset/image-prepull --timeout=600s

# Remember what is running, so an offline redeploy uses images the Pis have.
[[ -n "$TAG" ]] && echo "$TAG" > "$STATE_DIR/last-tag"

echo
scripts/where.sh
